package br.com.academico.model;

public class Campus {
	private int pkCampus;
	private String nomeCampus;
	
	
	public Campus() {
		
	}


	public int getPkCampus() {
		return pkCampus;
	}


	public void setPkCampus(int pkCampus) {
		this.pkCampus = pkCampus;
	}


	public String getNomeCampus() {
		return nomeCampus;
	}


	public void setNomeCampus(String nomeCampus) {
		this.nomeCampus = nomeCampus;
	}
	
	
	
}
