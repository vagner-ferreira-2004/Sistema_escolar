package br.com.academico.model;

public class Semestre {
	private int pkSemestre;
	private int ano;
	private int semestre;
	
	
	//Construtor vazio para instanciar objeto sem parâmetros
	public Semestre() {
		
	}


	public int getPkSemestre() {
		return pkSemestre;
	}


	public void setPkSemestre(int pkSemestre) {
		this.pkSemestre = pkSemestre;
	}


	public int getAno() {
		return ano;
	}


	public void setAno(int ano) {
		this.ano = ano;
	}


	public int getSemestre() {
		return semestre;
	}


	public void setSemestre(int semestre) {
		this.semestre = semestre;
	}

	//Getters and Setters

	
	
}
